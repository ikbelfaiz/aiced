import { test,expect } from '@playwright/test';
import { pipelineDiagnostics } from './pipeline-diagnostics';
pipelineDiagnostics();

test('Pipeline persists existing creation/status workflow and rejects a concurrent stale edit',async({page})=>{
  await page.goto('/clients');
  await page.getByLabel('Identifiant professionnel').fill('synthetic.operator.a');
  await page.getByLabel('Mot de passe',{exact:true}).fill(process.env.AICED_E2E_PASSWORD!);
  await page.getByRole('button',{name:'Connexion',exact:true}).click();
  await page.getByRole('button',{name:'Nouveau client',exact:true}).click();
  const name=`SYNTHETIQUE PIPELINE ${Date.now()}`;
  await page.getByLabel('Prénom (personne physique)',{exact:true}).fill('TEST');
  await page.getByLabel('Nom (personne physique)',{exact:true}).fill(name);
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
  await expect(page.getByRole('heading',{name:`TEST ${name}`,exact:true})).toBeVisible();
  const party=new URL(page.url()).pathname.split('/').pop()!;
  await page.getByRole('navigation',{name:'Sections de la fiche client'}).getByRole('button',{name:'Opportunités',exact:true}).click();
  await page.getByRole('button',{name:'Ajouter une opportunité',exact:true}).click();
  await page.getByLabel('Intitulé',{exact:true}).fill(name);
  await page.getByLabel('Estimation commerciale en TND (facultatif)').fill('123.456');
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('link',{name:'Opportunités',exact:true}).click();
  await page.getByLabel('Rechercher par dossier, titre ou notes').fill(name);
  await page.getByRole('button',{name:'Rechercher',exact:true}).click();
  await expect(page.locator('.pipeline-card')).toHaveCount(1);
  await expect(page.locator('.pipeline-card')).toContainText('123.456 TND');
  await page.getByRole('link',{name:`Ouvrir / modifier : ${name}`,exact:true}).click();
  await page.getByRole('button',{name:`Modifier ${name}`,exact:true}).click();
  await page.getByLabel('État commercial').selectOption('won');
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.getByRole('button',{name:`Modifier ${name}`,exact:true}).click();
  const id=new URL(page.url()).searchParams.get('opportunite')!;
  const csrf=(await(await page.request.get('/api/auth/csrf/')).json()).csrfToken;
  const api=`/api/clients/${party}/opportunities/`;
  expect((await page.request.patch(`${api}${id}/`,{headers:{'X-CSRFToken':csrf},data:{version:2,notes:'SYNTHETIC concurrent edit'}})).status()).toBe(200);
  await page.getByLabel('État commercial').selectOption('lost');
  await page.getByRole('button',{name:'Enregistrer',exact:true}).click();
  await expect(page.getByRole('dialog').getByRole('alert')).toContainText('Version obsolète');
  await page.getByRole('button',{name:'Annuler',exact:true}).click();
  for(let i=0;i<8;i++)expect((await page.request.post(api,{headers:{'X-CSRFToken':csrf},data:{title:`${name} ${i}`,status:'open'}})).status()).toBe(201);
  await page.getByRole('link',{name:'Opportunités',exact:true}).click();
  await page.getByLabel('Rechercher par dossier, titre ou notes').fill(name);
  await page.getByRole('button',{name:'Rechercher',exact:true}).click();
  await expect.poll(()=>new URL(page.url()).searchParams.get('search')).toBe(name);
  await expect(page.locator('.pagination')).toContainText('9 opportunité(s) · page 1');
  await page.getByLabel('Trier par',{exact:true}).selectOption('title');
  await expect.poll(()=>new URL(page.url()).searchParams.get('ordering')).toBe('title');
  await expect(page.locator('.pipeline-card')).toHaveCount(8);
  await page.getByRole('button',{name:'Suivant',exact:true}).click();
  await expect(page.locator('.pipeline-card')).toHaveCount(1);
  await page.getByLabel('Statut',{exact:true}).selectOption('won');
  await expect.poll(()=>new URL(page.url()).searchParams.get('status')).toBe('won');
  await page.reload();
  await expect(page.locator('.pipeline-card')).toHaveCount(1);
  await expect(page.locator('.pipeline-column')).toContainText('Gagnées (1)');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'../.local/ui-review/screens/pipeline-mobile.png',fullPage:true});
});

test('Pipeline hides cached cards on authorization failure and denies IT',async({page})=>{
  await page.goto('/opportunites');
  await page.getByLabel('Identifiant professionnel').fill('synthetic.operator.a');
  await page.getByLabel('Mot de passe',{exact:true}).fill(process.env.AICED_E2E_PASSWORD!);
  await page.getByRole('button',{name:'Connexion',exact:true}).click();
  await expect(page.locator('.pipeline-card').first()).toBeVisible();
  await page.getByRole('link',{name:'Clients',exact:true}).click();
  await page.route('**/api/opportunities/**',route=>route.fulfill({status:403,contentType:'application/json',body:'{}'}));
  await page.getByRole('link',{name:'Opportunités',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Impossible de charger le pipeline'})).toBeVisible();
  await expect(page.locator('.pipeline-card')).toHaveCount(0);
  await page.unroute('**/api/opportunities/**');
  await page.getByRole('button',{name:'Réessayer',exact:true}).click();
  await expect(page.locator('.pipeline-card').first()).toBeVisible();
  const context=await page.context().browser()!.newContext();
  try{
    const it=await context.newPage();await it.goto(new URL('/opportunites',page.url()).toString());
    await it.getByLabel('Identifiant professionnel').fill('synthetic.it.a');
    await it.getByLabel('Mot de passe',{exact:true}).fill(process.env.AICED_E2E_PASSWORD!);
    await it.getByRole('button',{name:'Connexion',exact:true}).click();
    await expect(it.getByRole('heading',{name:'Pipeline non autorisé'})).toBeVisible();
    expect((await it.request.get(new URL('/api/opportunities/',page.url()).toString())).status()).toBe(403);
  }finally{await context.close();}
});
